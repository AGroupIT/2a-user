import 'package:flutter/material.dart';

/// Shared animated circles for brand-gradient hero/header cards.
///
/// Keep this as a full-background layer:
/// `Stack(children: [const Positioned.fill(child: AnimatedHeroGlowBackdrop()), ...])`.
/// If it is placed inside the content padding, the circles visually detach from
/// the card edges.
class AnimatedHeroGlowBackdrop extends StatefulWidget {
  const AnimatedHeroGlowBackdrop({super.key});

  @override
  State<AnimatedHeroGlowBackdrop> createState() =>
      _AnimatedHeroGlowBackdropState();
}

class _AnimatedHeroGlowBackdropState extends State<AnimatedHeroGlowBackdrop>
    with SingleTickerProviderStateMixin {
  late final AnimationController _controller;

  @override
  void initState() {
    super.initState();
    _controller = AnimationController(
      vsync: this,
      duration: const Duration(milliseconds: 5600),
    )..repeat(reverse: true);
    _settleAfter(const Duration(seconds: 9));
  }

  void _settleAfter(Duration activeFor) {
    Future<void>.delayed(activeFor, () {
      if (!mounted || !_controller.isAnimating) return;
      _controller.animateTo(
        0.5,
        duration: const Duration(milliseconds: 650),
        curve: Curves.easeOutCubic,
      );
    });
  }

  @override
  void dispose() {
    _controller.dispose();
    super.dispose();
  }

  @override
  Widget build(BuildContext context) {
    return IgnorePointer(
      child: RepaintBoundary(
        child: AnimatedBuilder(
          animation: _controller,
          builder: (context, child) {
            final wave = Curves.easeInOutCubic.transform(_controller.value);
            final shift = (wave * 2) - 1;

            return Stack(
              clipBehavior: Clip.none,
              children: [
                Positioned(
                  right: -62,
                  top: -58,
                  child: Transform.translate(
                    offset: Offset(-10 * shift, 6 * shift),
                    child: _GlowCircle(
                      size: 154,
                      color: Colors.white.withValues(alpha: 0.13),
                    ),
                  ),
                ),
                Positioned(
                  right: 22,
                  bottom: -68,
                  child: Transform.translate(
                    offset: Offset(9 * shift, -7 * shift),
                    child: _GlowCircle(
                      size: 152,
                      color: Colors.white.withValues(alpha: 0.08),
                    ),
                  ),
                ),
                Positioned(
                  right: -14,
                  bottom: 16,
                  child: Transform.translate(
                    offset: Offset(5 * shift, -4 * shift),
                    child: _GlowCircle(
                      size: 82,
                      color: Colors.white.withValues(alpha: 0.08),
                    ),
                  ),
                ),
              ],
            );
          },
        ),
      ),
    );
  }
}

class _GlowCircle extends StatelessWidget {
  final double size;
  final Color color;

  const _GlowCircle({required this.size, required this.color});

  @override
  Widget build(BuildContext context) {
    return Container(
      width: size,
      height: size,
      decoration: BoxDecoration(shape: BoxShape.circle, color: color),
    );
  }
}
